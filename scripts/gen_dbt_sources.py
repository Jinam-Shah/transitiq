"""Regenerate dbt/models/staging/sources.yml from the silver contracts.

Run after changing pipelines/src/transitiq_pipelines/silver/contracts.py:
    python scripts/gen_dbt_sources.py
tests/test_dbt_contracts.py fails if the YAML and the contracts disagree.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "pipelines" / "src"))

from transitiq_pipelines.silver.contracts import SILVER_TABLES  # noqa: E402
from transitiq_pipelines.silver.publish import DUCKDB_TYPES  # noqa: E402

DESCRIPTIONS = {
    "subway_events": "One arrival/departure event per trip and stop (MBTA LAMP subway on-time "
    "performance), partitioned by service_date.",
    "alerts": "One row per alert version and informed entity (MBTA LAMP alerts history "
    "since 2018).",
    "weather_hourly": "Hourly weather for downtown Boston in UTC (Open-Meteo, CC BY 4.0).",
    "facilities": "Elevators and escalators (MBTA V3 API snapshot).",
    "gtfs_routes": "GTFS routes (current MBTA feed).",
    "gtfs_stops": "GTFS stops, platforms and stations.",
    "gtfs_trips": "GTFS scheduled trips.",
    "gtfs_stop_times": "GTFS scheduled stop times.",
    "gtfs_calendar": "GTFS weekly service calendars.",
    "gtfs_calendar_dates": "GTFS service exceptions.",
    "rt_vehicle_positions": "GTFS-Realtime vehicle positions, one row per vehicle per collector "
    "snapshot, partitioned by feed_date (UTC).",
    "rt_trip_updates": "GTFS-Realtime trip updates, one row per trip per snapshot with only the "
    "next stop prediction, partitioned by feed_date (UTC).",
}
FRESHNESS = {"subway_events": (2, 14)}


def main() -> None:
    lines = [
        "version: 2",
        "",
        "# GENERATED by scripts/gen_dbt_sources.py from the silver contracts. Do not edit by hand.",
        "",
        "sources:",
        "  - name: silver",
        "    schema: silver",
        "    description: Validated Iceberg tables exposed as DuckDB views by "
        "`transitiq-silver publish`.",
        "    tables:",
    ]
    for name, schema in SILVER_TABLES.items():
        lines += [f"      - name: {name}", f'        description: "{DESCRIPTIONS[name]}"']
        if name in FRESHNESS:
            warn, err = FRESHNESS[name]
            lines += [
                "        config:",
                "          loaded_at_field: _loaded_at",
                "          freshness:",
                f"            warn_after: {{count: {warn}, period: day}}",
                f"            error_after: {{count: {err}, period: day}}",
            ]
        lines += ["        columns:"]
        for f in schema:
            lines += [
                f"          - name: {f.name}",
                f"            data_type: {DUCKDB_TYPES[f.type].lower()}",
            ]
    out = ROOT / "dbt" / "models" / "staging" / "sources.yml"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(SILVER_TABLES)} tables)")


if __name__ == "__main__":
    main()
